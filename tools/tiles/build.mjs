// Renders every tile picture to app/src/assets/tiles/<id>.webp (480 × 480) and writes the registry.
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { TILES } from './tiles.mjs';
const out = new URL('../../app/src/assets/tiles/', import.meta.url).pathname;
const tmp = process.env.TILE_TMP ?? '/tmp/tiles-png';
mkdirSync(out, { recursive: true }); mkdirSync(tmp, { recursive: true });
const only = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }).catch(() => chromium.launch());
const p = await b.newPage({ viewport: { width: 480, height: 480 } });
for (const [id, svg] of Object.entries(TILES)) {
  if (only.length && !only.includes(id)) continue;
  await p.setContent(`<html><body style="margin:0">${svg}</body></html>`);
  await p.screenshot({ path: `${tmp}/${id}.png` });
  execFileSync('python3', ['-c', `from PIL import Image; Image.open('${tmp}/${id}.png').convert('RGB').save('${out}${id}.webp','WEBP',quality=88,method=6)`]);
}
await b.close();
const ids = Object.keys(TILES).sort();
writeFileSync(new URL('../../app/src/assets/tileImages.ts', import.meta.url).pathname,
  `// Generated by tools/tiles/build.mjs (iteration 2, DECISIONS D-94): drawn pictures for home tiles,\n// top-strip categories and sub-categories, one consistent style. Do not edit by hand.\nexport const tileImages: Record<string, number> = {\n${ids.map((id) => `  '${id}': require('./tiles/${id}.webp'),`).join('\n')}\n};\n`);
console.log('tiles', ids.length);

// names, with prices close to Nalgonda shelf prices in Oct 2026. Restaurant and home-food sellers are invented
// local names. Photos come from `images.ts`; products without a photo keep the bundled placeholder.
import type { Id, ItemType, Product } from '../types';

/** [label, price, mrp?, stock?] */
type V = [string, number, number?, number?];
/** [id, name, variants, subtitle?] */
type Row = [Id, string, V[], string?];

const PRODUCT = 'asset:product';

function group(categoryId: Id, rows: Row[], itemType: ItemType = 'product'): Product[] {
  return rows.map(([id, name, variants, subtitle]) => ({
    id,
    categoryId,
    name,
    ...(subtitle ? { subtitle } : {}),
    imageUrl: PRODUCT,
    itemType,
    // Meat does not count toward coupon minimums, as in the live app.
    couponExempt: itemType === 'meat',
    variants: variants.map(([label, price, mrp, stock], i) => ({ id: `${id}-${i + 1}`, label, price, mrp, stock: stock ?? 50 })),
  }));
}

